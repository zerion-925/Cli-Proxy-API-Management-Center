describe('persistent client meter authenticated transport', () => {
  test('uses central captured bearer auth and only the declared plugin path', async () => {
    let observed = '';
    const server = Bun.serve({
      hostname: '127.0.0.1',
      port: 0,
      fetch(request) {
        const url = new URL(request.url);
        observed = `${url.pathname}${url.search}|${request.headers.get('Authorization')}`;
        return Response.json(response);
      },
    });
    try {
      const apiBase = `http://127.0.0.1:${server.port}`;
      apiClient.setConfig({ apiBase, managementKey: 'synthetic-management-test' });
      const data = await fetchClientUsage(
        apiBase,
        '7d',
        'native_0123456789abcdef0123456789abcdef',
        new AbortController().signal
      );
      expect(data.totals.attempts).toBe(3);
      expect(observed).toBe(
        '/v0/management/client-usage-meter?range=7d&client=native_0123456789abcdef0123456789abcdef|Bearer synthetic-management-test'
      );
      expect(observed).not.toContain('/v8/management');
    } finally {
      server.stop(true);
      apiClient.setConfig({ apiBase: '', managementKey: '' });
    }
  });
  test('stale captured connection cannot dispatch unauthorized for a new session', async () => {
    const server = Bun.serve({
      hostname: '127.0.0.1',
      port: 0,
      fetch() {
        apiClient.setConfig({
          apiBase: 'http://synthetic-new-connection.invalid',
          managementKey: 'synthetic-new-session',
        });
        return Response.json({}, { status: 401 });
      },
    });
    try {
      const apiBase = `http://127.0.0.1:${server.port}`;
      apiClient.setConfig({ apiBase, managementKey: 'synthetic-old-session' });
      await expect(
        fetchClientUsage(apiBase, '24h', '', new AbortController().signal)
      ).rejects.toMatchObject({ status: 401, name: 'ApiError' });
    } finally {
      server.stop(true);
      apiClient.setConfig({ apiBase: '', managementKey: '' });
    }
  });
});

describe('persistent client meter contract', () => {
  test('accepts the wire response generated by the real official proxy and compiled plugin', () => {
    const wire = readFileSync(
      new URL('./fixtures/usage-meter-official-runtime.json', import.meta.url),
      'utf8'
    );
    const data = normalizeClientUsage(JSON.parse(wire));
    expect(data.totals.attempts).toBe(3);
    expect(data.totals.succeeded).toBe(2);
    expect(data.totals.failed).toBe(1);
    expect(data.totals.totalTokens).toBe(240);
    expect(data.totals.requests).toBeNull();
    expect(data.totals.cacheRate).toBeNull();
    expect(data.clients.length).toBe(2);
    expect(data.collection.duplicates).toBe(1);
    expect(wire).not.toContain('synthetic-client-key');
    expect(wire).not.toContain('synthetic-upstream-key');
    expect(wire).not.toContain('synthetic prompt');
  });
  test('preserves official plugin path, not core v8 or a legacy fallback', () => {
    expect(usageMeterUrl('http://localhost:8317/v8/management')).toBe(
      'http://localhost:8317/v0/management/client-usage-meter'
    );
  });
  test('normalizes canonical fields without conflating requests and attempts', () => {
    const data = normalizeClientUsage(response);
    expect(data.totals.attempts).toBe(3);
    expect(data.totals.requests).toBeNull();
    expect(data.totals.cacheRate).toBe(0.4);
    expect(data.totals.unknownTokenEvents).toBe(1);
    expect(data.clients[0]).not.toHaveProperty('label');
    expect(data.collection.state).toBe('partial');
    expect(data.pricingAvailable).toBe(false);
  });
  test('rejects raw-looking key identifiers before they can reach selectors or URLs', () => {
    expect(() =>
      normalizeClientUsage({
        ...response,
        clients: [{ id: 'sk-synthetic-secret-do-not-display', namespace: 'native' }],
      })
    ).toThrow();
  });
  test('rejects unavailable/malformed counters instead of fabricating zero', () => {
    expect(() => normalizeClientUsage({ ...response, totals: {} })).toThrow();
    expect(() => normalizeClientUsage({ ...response, schema_version: 2 })).toThrow();
    expect(() =>
      normalizeClientUsage({ ...response, totals: { ...totals, attempts: -1 } })
    ).toThrow();
    expect(() =>
      normalizeClientUsage({ ...response, totals: { ...totals, cache_rate: 9 } })
    ).toThrow();
  });
  test('preserves null rate and empty history', () => {
    const data = normalizeClientUsage({
      ...response,
      timeline: [],
      models: [],
      totals: { ...totals, cache_rate: null },
    });
    expect(data.totals.cacheRate).toBeNull();
    expect(data.timeline).toEqual([]);
  });
});
